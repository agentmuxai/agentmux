//! The app shortcuts the host forwards out of a focused browser pane. A browser pane is a native CEF child
//! window, so the app's own key handling never sees its keys. The list starts as the one generated from the
//! frontend's default table (`frontend/app/keybindings/host-keys.json`, pinned by `host-keys.test.ts`); when
//! the person's keybindings change the app sends the list its effective table gives (`set_host_keys`), which
//! replaces it until the next push (docs/specs/SPEC_KEYBOARD_SHORTCUTS_SETTINGS_2026_11_06.md §7).

use parking_lot::RwLock;
use std::sync::{Arc, LazyLock};

/// One app shortcut the host forwards: the modifiers and Windows virtual-key code of a key in the frontend's
/// shortcut table.
#[derive(Debug, Clone, PartialEq, serde::Deserialize)]
pub(crate) struct HostKey {
    pub(crate) command: String,
    /// The table key ("ctrl+shift+t"), sent back so the app can check the person's own keybindings still bind it.
    pub(crate) source: String,
    ctrl: bool,
    shift: bool,
    alt: bool,
    meta: bool,
    vk: i32,
}

#[derive(Debug, serde::Deserialize)]
struct HostKeys {
    mac: Vec<HostKey>,
    /// Windows.
    other: Vec<HostKey>,
    /// Linux: `other`, except where the table gives Linux its own keys because the desktop takes the shared ones.
    linux: Vec<HostKey>,
}

static DEFAULT_KEYS: LazyLock<HostKeys> = LazyLock::new(|| {
    serde_json::from_str(include_str!("../../../../frontend/app/keybindings/host-keys.json"))
        .expect("frontend/app/keybindings/host-keys.json is generated by a test and must parse")
});

/// What the app last pushed for this platform; `None` until it does (the generated list applies).
static PUSHED: RwLock<Option<Arc<Vec<HostKey>>>> = RwLock::new(None);

/// A push is a handful of keys; this keeps a bad one from holding the key handler up.
const MAX_PUSHED: usize = 256;

/// The key a browser pane's key press is, if it is one the app wants.
pub(crate) fn host_key_for(ctrl: bool, shift: bool, alt: bool, meta: bool, vk: i32, mac: bool) -> Option<HostKey> {
    let matches = |k: &&HostKey| k.ctrl == ctrl && k.shift == shift && k.alt == alt && k.meta == meta && k.vk == vk;
    if let Some(pushed) = PUSHED.read().as_ref() {
        return pushed.iter().find(matches).cloned();
    }
    let keys = if mac {
        &DEFAULT_KEYS.mac
    } else if cfg!(target_os = "linux") {
        &DEFAULT_KEYS.linux
    } else {
        &DEFAULT_KEYS.other
    };
    keys.iter().find(matches).cloned()
}

fn replace(keys: Vec<HostKey>) {
    *PUSHED.write() = Some(Arc::new(keys));
}

/// IPC `set_host_keys`: the app's effective list. Refuses a list it cannot use rather than keep part of it.
pub(crate) fn set_host_keys(args: &serde_json::Value) -> Result<serde_json::Value, String> {
    let keys: Vec<HostKey> = serde_json::from_value(args.get("keys").cloned().ok_or("set_host_keys: missing keys")?)
        .map_err(|e| format!("set_host_keys: {e}"))?;
    if keys.len() > MAX_PUSHED {
        return Err(format!("set_host_keys: at most {MAX_PUSHED} keys"));
    }
    if let Some(bad) = keys.iter().find(|k| k.command.is_empty() || !(1..=254).contains(&k.vk)) {
        return Err(format!("set_host_keys: {:?} is not a usable key", bad.source));
    }
    tracing::info!("[app-shortcut] host keys replaced: {} keys", keys.len());
    replace(keys);
    Ok(serde_json::json!({ "count": PUSHED.read().as_ref().map_or(0, |k| k.len()) }))
}

/// The generated list for this platform, for a test.
#[cfg(test)]
pub(crate) fn default_keys(mac: bool) -> &'static [HostKey] {
    if mac {
        &DEFAULT_KEYS.mac
    } else if cfg!(target_os = "linux") {
        &DEFAULT_KEYS.linux
    } else {
        &DEFAULT_KEYS.other
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The pushed list is process-wide: one test at a time touches it.
    static LOCK: parking_lot::Mutex<()> = parking_lot::Mutex::new(());

    fn clear() {
        *PUSHED.write() = None;
    }

    #[test]
    fn a_push_replaces_the_generated_list_until_the_next_push() {
        let _g = LOCK.lock();
        clear();
        // Ctrl+Shift+T is new tab in the generated list (⌘T on macOS).
        let (ctrl, meta, mac) = if cfg!(target_os = "macos") { (false, true, true) } else { (true, false, false) };
        let shift = !mac;
        assert_eq!(host_key_for(ctrl, shift, false, meta, 0x54, mac).map(|k| k.command), Some("tab:new".to_string()));

        let pushed = serde_json::json!({ "keys": [
            { "command": "tab:new", "source": "ctrl+shift+y", "ctrl": true, "shift": true, "alt": false, "meta": false, "vk": 0x59 },
        ] });
        assert_eq!(set_host_keys(&pushed).unwrap()["count"], 1);
        assert_eq!(host_key_for(true, true, false, false, 0x59, false).map(|k| k.source), Some("ctrl+shift+y".to_string()));
        // The old key is no longer forwarded: the page gets it.
        assert_eq!(host_key_for(ctrl, shift, false, meta, 0x54, mac), None);

        // An empty push is a list with nothing in it, not a return to the generated one.
        assert_eq!(set_host_keys(&serde_json::json!({ "keys": [] })).unwrap()["count"], 0);
        assert_eq!(host_key_for(true, true, false, false, 0x59, false), None);
        clear();
    }

    #[test]
    fn a_list_it_cannot_use_changes_nothing() {
        let _g = LOCK.lock();
        clear();
        let key = |vk: i64, command: &str| serde_json::json!({ "command": command, "source": "x", "ctrl": true, "shift": false, "alt": false, "meta": false, "vk": vk });
        for keys in [
            serde_json::json!([key(0, "tab:new")]),
            serde_json::json!([key(300, "tab:new")]),
            serde_json::json!([key(0x59, "")]),
            serde_json::json!("not a list"),
            serde_json::json!((0..=MAX_PUSHED).map(|_| key(0x59, "tab:new")).collect::<Vec<_>>()),
        ] {
            assert!(set_host_keys(&serde_json::json!({ "keys": keys })).is_err(), "{keys}");
        }
        assert!(set_host_keys(&serde_json::json!({})).is_err());
        assert!(PUSHED.read().is_none());
    }

    #[test]
    fn the_generated_list_parses_and_has_the_shared_keys() {
        assert!(default_keys(false).iter().any(|k| k.command == "tab:new" && k.ctrl && k.shift && k.vk == 0x54));
        assert!(DEFAULT_KEYS.linux.iter().any(|k| k.command == "tab:new" && k.ctrl && k.shift && k.vk == 0x54));
    }
}
