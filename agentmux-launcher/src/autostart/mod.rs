    ///
    /// ```text
    /// cargo test -p agentmux-launcher --release -- --ignored autostart_round_trip
    /// ```
    ///
    /// This is the WS4 "independently-testable uninstall path" made literal:
    /// it verifies removal by asking the platform, not by trusting our own
    /// bookkeeping. Self-cleaning — it disables at the end, and asserts the
    /// artifact is actually gone.
    #[test]
    #[ignore = "mutates real login configuration; run explicitly with --ignored"]
    fn autostart_round_trip_against_the_real_platform_registry() {
        // Refuse to run if the user already has autostart configured, rather
        // than clobbering (and then deleting) their real registration.
        assert!(
            !is_enabled(),
            "autostart already enabled on this machine — refusing to overwrite a real registration"
        );

        let exe = std::env::current_exe().expect("current_exe");
        enable(&exe, "test").expect("enable should succeed");
        assert!(is_enabled(), "enable() must be observable through the platform");

        // Idempotent re-enable (the upgrade path: repoint at a new exe).
        enable(&exe, "test").expect("re-enable should replace, not fail");
        assert!(is_enabled());

        disable().expect("disable should succeed");
        assert!(!is_enabled(), "disable() must actually remove the artifact");

        // Safe to call unconditionally — the property an uninstaller needs.
        disable().expect("disable must be idempotent");
    }

