//! Native pre-splash for Windows: a borderless layered popup showing the
//! AgentMux brain logo (pulsing) while startup runs, with a live startup
//! telemetry panel below the logo.
//!
//! ## Layout
//!
//! ```
//! ┌─ SPLASH_W × SPLASH_H ────────────────────────────────┐
//! │  solid BG_COLOR                                       │
//! │   ┌─ BRAIN_W × BRAIN_H ─┐  ← brain region            │
//! │   │ brain (pulsing)     │                             │
//! │   └─────────────────────┘                             │
//! │                                                       │
//! │  Saga recovery          23ms                          │
//! │  Migrations          2,341ms                          │
//! │    0001 Legacy data      147ms +                      │
//! │    0009 Transcript     2,187ms +                      │
//! │  Channel pruner          89ms  freed 612 MB           │
//! │  Backend startup        134ms                         │
//! │  CEF init               312ms                         │
//! │  Frontend init    >  0.4s                             │
//! │  ─────────────────────────────────────────────────── │
//! │  area54@DESKTOP-XYZ · v0.49.3                        │  ← footer
//! └──────────────────────────────────────────────────────┘
//! ```
//!
//! Startup telemetry events are delivered via a `std::sync::mpsc::Receiver`
//! passed to `spawn_splash`.  Each animation frame (~60 fps) drains the
//! receiver and updates the stage list.  When the CEF host signals the
//! dismiss Win32 event (from `on_load_end`), the splash freezes, holds for
//! `AGENTMUX_SPLASH_HOLD_MS` ms (default 2000), then fades out.

#![cfg(target_os = "windows")]

use std::thread;
use std::time::Instant;
use windows_sys::Win32::Foundation::*;
use windows_sys::Win32::Graphics::Gdi::*;
use windows_sys::Win32::System::LibraryLoader::GetModuleHandleW;
use windows_sys::Win32::System::Threading::*;
