/**
 * P0b of SPEC_MESSAGE_ORIGIN_AND_ONE_CONTAINER_2026_10_25.md (§2.1 row 17, §7 "CLI message"): a
 * turn the CLI wrote itself (a Monitor event, a system reminder, a hook's output) is a note, never
 * the human's style. The classification only narrows: a turn moves out of the human style when the
 * whole payload is CLI wrapper blocks, and never the other way.
 */
import { cleanup, render } from "@solidjs/testing-library";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { parseTaskNotification } from "./activity/tool-adapter";
import { injectedTurn, isCliTurn, parseCliTurn } from "./cli-wrappers";
import { SystemNoteBlock } from "./components/SystemNoteBlock";
import { ClaudeCodeStreamParser } from "./stream-parser";
import { startsTurn } from "./live-feed";
import type { DocumentNode, SystemNoteNode, UserMessageNode } from "./types";

afterEach(() => cleanup());

const MONITOR = [
    "<task-notification>",
    "<task-id>bk3x9</task-id>",
    "<summary>Monitor event: PR #5874 checks changed</summary>",
    "<event>nextest (windows-latest) completed: success</event>",
    "</task-notification>",
].join("\n");
const WITH_ID = [
    "<task-notification>",
    "<task-id>bk3x9</task-id>",
    "<tool-use-id>toolu_01ABC</tool-use-id>",
    "<status>completed</status>",
    "<summary>Background command finished</summary>",
    "</task-notification>",
].join("\n");
const REMINDER = "<system-reminder>\nThe task tools haven't been used recently.\n</system-reminder>";
const HOOK = "<user-prompt-submit-hook>\nHook says: remember the changeset.\n</user-prompt-submit-hook>";
const LOCAL = "<local-command-caveat>Caveat: these messages were generated by the user while running local commands.</local-command-caveat>";

/** Each input and where it ends up. `cli` leaves the human's style; `human` stays exactly as it was. */
const TABLE: { name: string; input: string; kind: "cli" | "human" }[] = [
    { name: "a Monitor event with no tool-use-id", input: MONITOR, kind: "cli" },
    { name: "a task notification with a tool-use-id", input: WITH_ID, kind: "cli" },
    { name: "a system reminder alone", input: REMINDER, kind: "cli" },
    { name: "hook output alone", input: HOOK, kind: "cli" },
    { name: "a local command caveat", input: LOCAL, kind: "cli" },
    { name: "two wrapper blocks in one turn", input: `${REMINDER}\n\n${HOOK}`, kind: "cli" },
    { name: "wrapper blocks with surrounding whitespace", input: `\n  ${REMINDER}  \n`, kind: "cli" },
    { name: "a person's plain message", input: "fix the build", kind: "human" },
    { name: "a person's message that mentions a tag inline", input: "why does <system-reminder> show up in my pane?", kind: "human" },
    { name: "a person's message that quotes a whole block and adds words", input: `${REMINDER}\nwhat is this?`, kind: "human" },
    { name: "words before a block", input: `look: ${MONITOR}`, kind: "human" },
    { name: "an unclosed wrapper", input: "<system-reminder>\nnever closed", kind: "human" },
    { name: "a tag the CLI does not wrap in", input: "<b>bold</b>", kind: "human" },
    { name: "an empty message", input: "", kind: "human" },
];

describe("T0: a turn only ever moves out of the human style, never into it", () => {
    for (const row of TABLE) {
        it(`${row.name}: ${row.kind}`, async () => {
            expect(parseCliTurn(row.input) !== null).toBe(row.kind === "cli");
            const nodes = await new ClaudeCodeStreamParser().parseEvent({ type: "user_message", message: row.input });
            const human = nodes.filter((n): n is UserMessageNode => n.type === "user_message");
            if (row.kind === "human") {
                expect(nodes.some(isCliTurn)).toBe(false);
                if (row.input.trim() !== "") expect(human.map((n) => n.message)).toEqual([row.input]);
            } else {
                expect(human).toEqual([]);
                expect(nodes.filter(isCliTurn)).toHaveLength(1);
            }
        });
    }
});

describe("a CLI turn as a note", () => {
    let parser: ClaudeCodeStreamParser;
    beforeEach(() => {
        parser = new ClaudeCodeStreamParser();
    });
    const noteOf = async (message: string): Promise<SystemNoteNode> => {
        const nodes = await parser.parseEvent({ type: "user_message", message });
        return nodes.find(isCliTurn) as SystemNoteNode;
    };

    it("shows a Monitor event's summary and event, not its XML", async () => {
        const note = await noteOf(MONITOR);
        expect(note.text).toBe("Monitor event: PR #5874 checks changed\nnextest (windows-latest) completed: success");
        expect(note.source).toBe("cli");
        expect(note.raw).toBe(MONITOR);
    });

    it("shows a reminder's own words", async () => {
        expect((await noteOf(REMINDER)).text).toBe("The task tools haven't been used recently.");
    });

    it("names a notification that has nothing to read by its status", () => {
        const bare = "<task-notification><tool-use-id>t1</tool-use-id><status>failed</status></task-notification>";
        expect(parseCliTurn(bare)?.text).toBe("Background task failed");
    });

    it("emits nothing for a wrapper with no text at all", async () => {
        const nodes = await parser.parseEvent({ type: "user_message", message: "<system-reminder>  </system-reminder>" });
        expect(nodes).toEqual([]);
    });

    it("starts a turn, as the user message it replaces did", async () => {
        const note = await noteOf(MONITOR);
        expect(startsTurn(note as DocumentNode)).toBe(true);
    });

    it("is classified the same on replay, with the line's stored time", async () => {
        const replay = new ClaudeCodeStreamParser({ isReplay: true });
        const nodes = await replay.parseEvent({ type: "user_message", message: MONITOR, timestamp: 1_700_000_000_000 });
        const note = nodes.find(isCliTurn) as SystemNoteNode;
        expect(note.timestamp).toBe(1_700_000_000_000);
        expect(nodes.some((n) => n.type === "user_message")).toBe(false);
        const undated = await new ClaudeCodeStreamParser({ isReplay: true }).parseEvent({ type: "user_message", message: MONITOR });
        expect((undated.find(isCliTurn) as SystemNoteNode).timestamp).toBeUndefined();
    });
});

describe("the dock still reads a task notification", () => {
    it("reads the tool-use-id and status from the note's raw text, as it did from the user message", async () => {
        const nodes = await new ClaudeCodeStreamParser().parseEvent({ type: "user_message", message: WITH_ID });
        const turn = injectedTurn(nodes[0])!;
        expect(parseTaskNotification(turn.text)).toEqual({ toolUseId: "toolu_01ABC", status: "done" });
    });

    it("reads a plain user message the same way", () => {
        const user: UserMessageNode = { type: "user_message", id: "u1", message: WITH_ID, timestamp: 5, isStartup: false };
        expect(injectedTurn(user)).toEqual({ text: WITH_ID, timestamp: 5 });
    });

    it("has nothing to read from an AgentMux note or a CLI note without raw text", () => {
        expect(injectedTurn({ type: "system_note", id: "n", text: "x" })).toBeNull();
        expect(injectedTurn({ type: "system_note", id: "n", text: "x", source: "cli" })).toBeNull();
    });
});

describe("SystemNoteBlock for a CLI turn", () => {
    it("is labelled CLI message and is never the human's turn", () => {
        const node: SystemNoteNode = { type: "system_note", id: "n1", text: "Monitor event: PR #5874 checks changed", source: "cli", raw: MONITOR };
        const { container } = render(() => <SystemNoteBlock node={node} />);
        const root = container.querySelector(".agent-system-note")!;
        expect(root.classList.contains("agent-system-note--cli")).toBe(true);
        expect(root.querySelector(".agent-system-note__label")?.textContent).toContain("CLI message");
        expect(root.querySelector(".agent-system-note__label")?.textContent).not.toContain("AgentMux");
        expect(root.querySelector(".agent-system-note__text")?.textContent).toBe("Monitor event: PR #5874 checks changed");
        expect(container.querySelector(".agent-user-message")).toBeNull();
    });

    it("keeps the AgentMux label for AgentMux's own note", () => {
        const { container } = render(() => <SystemNoteBlock node={{ type: "system_note", id: "n2", text: "upgraded" }} />);
        expect(container.querySelector(".agent-system-note__label")?.textContent).toContain("AgentMux");
        expect(container.querySelector(".agent-system-note--cli")).toBeNull();
    });
});
