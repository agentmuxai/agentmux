/**
 * A single terminal-style activity-log entry — emitted throughout the
 * pane lifecycle: launch flow (CLI resolution, install progress, auth
 * check, login poll), subprocess lifecycle (spawned / turn complete /
 * exit codes), slash-command outcomes, history pagination, subagent
 * events, errors. Collected into an array by `useActivityLog` and written
 * directly into the shell terminal (agent-view.tsx's `log`/
 * `handleShellTermReady`) rather than a separate panel.
 */
export interface LogLine {
    /** Stable id used as the key for per-line expanded-state (hover strip
     *  expand button). Generated by `useActivityLog.append`. */
    id: string;
    tag: string; // "agent", "cli", "auth", "env", "error", "install", etc.
    text: string;
    level?: "info" | "error" | "warn";
    /** Unix ms when the line was ingested. Shown by the per-line hover
     *  strip, same pattern as document nodes. */
    timestamp: number;
}

/**
 * Initialization question asked by the CLI during startup
 */
export interface InitQuestion {
    type: "theme" | "login" | "generic" | "other";
    text?: string;
    prompt?: string;
    options?: string[];
    expectsInput?: boolean;
}

/**
 * State of the CLI initialization process
 */
export type InitState = {
    phase: "spawning" | "awaiting_response" | "processing" | "ready" | "error";
    message?: string;
    question?: InitQuestion;
    error?: string;
};

/**
 * Document state (managed by Jotai atoms)
 */
export interface DocumentState {
    collapsedNodes: Set<string>; // Rows the user closed that are open by default (agent messages, sensitive jekts, content-first tools)
    /**
     * Nodes the user has clicked to PIN expanded. For tool nodes this opens
     * the portal overlay with tool-specific content; for other kinds this is
     * used by future expansion surfaces. Default is collapsed — see
     * docs/specs/tool-collapse.md.
     */
    pinnedNodes: Set<string>;
    /**
     * Rows currently held EXPANDED after arriving live on screen: a tool that
     * finished there (added on its active→inactive transition, or on a fast
     * finish seen already done), or a jekt that came in
     * (virtualization/live-arrival.ts). Removed once the row scrolls off the
     * top of the viewport (latched collapse), replacing the old 3 s
     * post-completion timer. Loaded history never arrives live, so it's never
     * added and renders collapsed. Named `expandedTools` until jekts joined.
     * See docs/specs/PLAN_TOOL_BLOCK_SCROLL_DRIVEN_COLLAPSE_2026_06_16.md.
     */
    heldOpenNodes: Set<string>;
    scrollPosition: number;
    selectedNode: string | null; // For keyboard navigation
    filter: FilterState;
}

export interface FilterState {
    showThinking: boolean; // Hide thinking by default
    showSuccessfulTools: boolean; // Show successful tools
    showFailedTools: boolean; // Always show failures
    showIncoming: boolean; // Show incoming messages
    showOutgoing: boolean; // Show outgoing messages
}

/**
 * Streaming state — telemetry sub-object on the agent-pane reducer.
 *
 * PR G dropped the legacy `active: boolean` field; "is the stream
 * subscribed?" is now derived from the reducer's `lastEventMs !== null`
 * (or the {@link isStreamSubscribed} selector). The remaining fields
 * are write-only telemetry consumed by the reducer for buffer
 * accounting and the stuck-stream watchdog.
 */
export interface StreamingState {
    agentId: string | null;
    bufferSize: number; // Number of events buffered
    lastEventTime: number;
}

/**
 * Shared logging callback passed into hooks and flows.
 * Implementations append a tagged line to the launch-log document.
 */
export type LogFn = (tag: string, text: string, level?: "info" | "error" | "warn") => void;

/**
 * Runtime configuration for agent pane controls.
 * Stored in block metadata as "agent:runtime".
 * Applied as CLI flags on each turn (between --resume spawns).
 */
export type PermissionMode = "bypass" | "auto" | "acceptEdits" | "plan" | "default";

// "ultra": some Codex models' deepest level (their account's list says which
// levels each model takes, runtime-capabilities.ts effortLevels).
export type EffortLevel = "low" | "medium" | "high" | "xhigh" | "max" | "ultra";

export interface AgentRuntimeConfig {
    permissionMode: PermissionMode;
    // Provider-scoped model string (a value from the active provider's
    // `models` list).
    model: string;
    effort: EffortLevel;
}

