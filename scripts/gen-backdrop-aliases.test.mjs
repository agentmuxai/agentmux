import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { dependentAliases, expected, mappedNames, renderAliases, rootDefaults, varsIn } from "./gen-backdrop-aliases.mjs";

const mapped = { surface: { "--bg": "x" }, ink: { "--fg": "--ink-text" }, channels: ["--accent-rgb"] };

describe("rootDefaults", () => {
    it("takes the custom properties set on :root itself, the last one winning, and nothing in an at-rule or another selector", () => {
        const scss = `
            :root { --a: 1; --b: var(--a); --a: 2; }
            :root, .dense { --c: 3; }
            .other { --d: 4; }
            @media (min-width: 1px) { :root { --e: 5; } }
            :root:not([data-theme]) { --f: 6; }
        `;
        expect([...rootDefaults(scss)]).toEqual([
            ["--a", "2"],
            ["--b", "var(--a)"],
            ["--c", "3"],
        ]);
    });
});

describe("dependentAliases", () => {
    const defaults = new Map([
        ["--bg", "#111"],
        ["--fg", "#eee"],
        ["--accent-rgb", "1, 2, 3"],
        ["--line", "var(--fg)"],
        ["--line-soft", "color-mix(in srgb, var(--line) 40%, transparent)"],
        ["--panel", "var(--bg)"],
        ["--tint", "rgba(var(--accent-rgb), 0.2)"],
        ["--plain", "12px"],
        ["--other", "var(--plain)"],
    ]);

    it("finds what reads a mapped token, directly or through other aliases, in file order", () => {
        expect(dependentAliases(defaults, mapped)).toEqual(["--line", "--line-soft", "--panel", "--tint"]);
    });

    it("leaves out the mapped tokens themselves and what depends on nothing mapped", () => {
        const names = dependentAliases(defaults, mapped);
        for (const name of mappedNames(mapped)) expect(names).not.toContain(name);
        expect(names).not.toContain("--plain");
        expect(names).not.toContain("--other");
    });

    it("follows a chain written before the alias it reads", () => {
        const later = new Map([
            ["--first", "var(--second)"],
            ["--second", "var(--fg)"],
        ]);
        expect(dependentAliases(later, mapped)).toEqual(["--first", "--second"]);
    });
});

describe("renderAliases", () => {
    it("writes one [data-backdrop] rule with each alias at its :root value", () => {
        const out = renderAliases(new Map([["--fg", "#eee"], ["--line", "var(--fg)"], ["--plain", "1px"]]), mapped);
        expect(out).toContain("[data-backdrop] {\n    --line: var(--fg);\n}");
        expect(out).not.toContain("--plain");
        expect(out).toContain("@generated by scripts/gen-backdrop-aliases.mjs");
    });

    it("reads var() names, with a fallback or without", () => {
        expect(varsIn("color-mix(in srgb, var(--a) 5%, var( --b, red))")).toEqual(["--a", "--b"]);
    });
});

describe("_aliases.scss", () => {
    it("is what the generator writes now: run `node scripts/gen-backdrop-aliases.mjs` after changing theme.scss or mapped-tokens.json", () => {
        const file = join(dirname(fileURLToPath(import.meta.url)), "../frontend/app/backdrop/_aliases.scss");
        expect(readFileSync(file, "utf8")).toBe(expected());
    });
});
