// gen-ipc-catalog.mjs — writes, and checks, the host command catalog of the IPC docs page.
//
// The architecture audit of 2026-11-01 (finding 5) found the host command tables of
// the docs site's IPC catalog page written by hand and drifting: documented commands the
// host did not have, real ones missing. A list a person keeps is a list that goes stale, so the
// catalog is now read out of `route_command`'s `match cmd` (crates/cef/src/ipc.rs) and
// the stub list (crates/cef/src/commands/stubs.rs) and written between two markers in the
// page. The page keeps its prose around the markers; the block between them is generated.
//
// For each command the catalog gives: the handler it calls ("in the arm" when the arm
// holds the code itself), whether it runs inline, awaits or hops to a blocking thread,
// whether it reads its arguments, and the comment written above the arm in the code. It
// does not give argument or return shapes: those live in the handlers, and a hand-copied
// shape drifts the way the old tables did.
//
// Usage (from the root of the agentmux code):
//   node scripts/gen-ipc-catalog.mjs --page <file> [--code <root>] --check   exit 1 when the page differs
//   node scripts/gen-ipc-catalog.mjs --page <file> [--code <root>] --write   rewrite the block
//   node scripts/gen-ipc-catalog.mjs [--code <root>]                                  print the block
//
// agentmux-docs runs `--check` against its pinned checkout of the code, so a pin bump that
// adds or drops a command fails until the page is regenerated with `--write`.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { closeOf } from "./check-function-sizes.mjs";
import { isMain } from "./lib/is-main.mjs";
import { maskRust } from "./lib/source-mask.mjs";

export const BEGIN = "<!-- ipc-catalog:begin (generated by scripts/gen-ipc-catalog.mjs from route_command; do not edit by hand) -->";
export const END = "<!-- ipc-catalog:end -->";

const IPC_RS = "crates/cef/src/ipc.rs";
const STUBS_RS = "crates/cef/src/commands/stubs.rs";
const NOTE_MAX = 300;

/** The index of the first non-space character at or after `i` in `m`. */
function skipWs(m, i) {
    while (i < m.length && /\s/.test(m[i])) i++;
    return i;
}

/** The index of the first character at or after `i` in `src` that is not whitespace or a comment. */
function skipTrivia(src, i) {
    for (;;) {
        while (i < src.length && /\s/.test(src[i])) i++;
        if (src[i] === "/" && src[i + 1] === "/") {
            while (i < src.length && src[i] !== "\n") i++;
        } else if (src[i] === "/" && src[i + 1] === "*") {
            const e = src.indexOf("*/", i + 2);
            i = e < 0 ? src.length : e + 2;
        } else return i;
    }
}

/** The index of `target` (one character) at bracket depth 0, from `from` up to `limit`, or -1. */
function topLevel(m, from, limit, target) {
    let depth = 0;
    for (let j = from; j < limit; j++) {
        const c = m[j];
        if (c === "(" || c === "[" || c === "{") depth++;
        else if (c === ")" || c === "]" || c === "}") depth--;
        else if (depth === 0 && c === target) return j;
    }
    return -1;
}

/** The index of the `=>` that ends the pattern starting at `from`, at depth 0, or -1. */
function arrowAfter(m, from, limit) {
    let depth = 0;
    for (let j = from; j < limit; j++) {
        const c = m[j];
        if (c === "(" || c === "[" || c === "{") depth++;
        else if (c === ")" || c === "]" || c === "}") depth--;
        else if (depth === 0 && c === "=" && m[j + 1] === ">") return j;
    }
    return -1;
}

/**
 * What the comments in `gap` (the text between the end of one arm and the start of the next)
 * say: `banner` is the last `// ---- Title ----` line, `notes` the comment lines directly
 * above the arm, with no blank line or banner between them and it. The first line of the gap
 * is the tail of the previous arm's line and the last is the arm's own indent: neither counts.
 */
function readGap(gap) {
    const lines = gap.split("\n");
    let banner = null;
    let notes = [];
    for (const raw of lines.slice(1, -1)) {
        const t = raw.trim();
        if (!t.startsWith("//")) {
            notes = [];
            continue;
        }
        const text = t.replace(/^\/\/+!?\s?/, "").trim();
        const b = /^-{2,}\s*(.+?)\s*-{2,}$/.exec(text);
        if (b) {
            banner = b[1];
            notes = [];
        } else if (text) notes.push(text);
    }
    return { banner, notes };
}

/** Plain text for a table cell: one line, no pipes that would split the row. */
function cell(text) {
    return text.replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
}

/** Roots of a path that wrap or support a call rather than being the handler: the standard library, tokio, serde, primitives. */
const NOT_A_HANDLER = new Set(["std", "core", "alloc", "tokio", "serde", "serde_json", "tracing", "cef", "u8", "u16", "u32", "u64", "usize", "i32", "i64", "f32", "f64", "bool", "str"]);
/** Roots of calls that check a precondition before the arm's work (`dev_mode::require()?`). */
const GUARDS = new Set(["dev_mode"]);
/** Methods on `state.<field>` that only reach a value; the arm's real work is elsewhere. */
const PLUMBING = new Set(["lock", "clone", "read", "write", "get", "borrow", "load", "len"]);

/**
 * The function an arm dispatches to, from its (masked) body: the first path call such as
 * `commands::window::close_window(` whose root is not the standard library, tokio, serde, a
 * primitive or a type (a capitalised root, as in `Duration::from_millis(`), else the first
 * `state.field.method(` that is not plumbing, else "in the arm". A function handed to `spawn_blocking` by name counts. A heuristic: where the arm
 * does its work in more than one place, the page names the first.
 */
export function handlerOf(body) {
    // A function handed to the blocking pool by name, not called: `spawn_blocking(commands::x::run)`.
    const direct = /\bspawn_blocking\s*\(\s*((?:crate::)?[a-z_][a-z0-9_]*(?:::[A-Za-z_][A-Za-z0-9_]*)+)\s*[,)]/.exec(body);
    if (direct) return direct[1].replace(/^crate::/, "");
    for (const call of body.matchAll(/\b((?:crate::)?[A-Za-z_][A-Za-z0-9_]*(?:::[A-Za-z_][A-Za-z0-9_]*)+)\s*\(/g)) {
        const path = call[1].replace(/^crate::/, "");
        const root = path.split("::")[0];
        if (NOT_A_HANDLER.has(root) || /^[A-Z]/.test(root) || GUARDS.has(root)) continue;
        return path;
    }
    for (const m of body.matchAll(/\bstate\.([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)\s*\(/g)) {
        if (!PLUMBING.has(m[2])) return `state.${m[1]}.${m[2]}`;
    }
    return "in the arm";
}

/**
 * The arms of `match cmd` in `route_command` of `src`, in source order:
 * `{ names, group, note, handler, runs, args }`. An empty list when the function is not found.
 */
export function routeCommandEntries(src) {
    const m = maskRust(src);
    const fn = m.search(/\bfn route_command\b/);
    if (fn < 0) return [];
    const mt = /\n[ \t]*match cmd\s*\{/.exec(m.slice(fn));
    if (!mt) return [];
    const open = fn + mt.index + mt[0].length - 1;
    const close = closeOf(m, open);
    if (close < 0) return [];

    const out = [];
    let group = "Other";
    let i = open + 1;
    while (i < close) {
        const start = skipTrivia(src, i);
        if (start >= close) {
            group = readGap(src.slice(i, close)).banner ?? group;
            break;
        }
        const gap = readGap(src.slice(i, start));
        if (gap.banner) group = gap.banner;
        const arrow = arrowAfter(m, start, close);
        if (arrow < 0) break;
        const names = [...src.slice(start, arrow).matchAll(/"([^"]*)"/g)].map((x) => x[1]);
        const bodyStart = skipWs(m, arrow + 2);
        // `end` is the index just past the arm's body; `next` is where the next arm's gap starts.
        let end;
        let next;
        if (m[bodyStart] === "{") {
            end = closeOf(m, bodyStart) + 1;
            const after = skipWs(m, end);
            next = m[after] === "," ? after + 1 : end;
        } else {
            const comma = topLevel(m, bodyStart, close, ",");
            end = comma < 0 ? close : comma;
            next = comma < 0 ? close : comma + 1;
        }
        const body = m.slice(bodyStart, end);
        if (names.length) {
            const handler = handlerOf(body);
            out.push({
                names,
                group,
                note: gap.notes.join(" "),
                handler,
                runs: /\bspawn_blocking\b/.test(body) ? "blocking" : /\.await\b/.test(body) ? "async" : "inline",
                args: /\bargs\b/.test(body),
            });
        }
        i = next;
    }
    return out;
}

/** The command names `is_stub_command` accepts, from the source of stubs.rs. */
export function stubNames(stubSrc) {
    const m = maskRust(stubSrc);
    const fn = m.search(/\bfn is_stub_command\b/);
    if (fn < 0) return [];
    const mt = /matches!\s*\(/.exec(m.slice(fn));
    if (!mt) return [];
    const open = fn + mt.index + mt[0].length - 1;
    const close = closeOf(m, open);
    if (close < 0) return [];
    return [...stubSrc.slice(open, close).matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

/** The Markdown block (without the markers) for the entries and stubs. */
export function renderCatalog(entries, stubs) {
    const names = entries.flatMap((e) => e.names).filter((n) => !stubs.includes(n));
    const groups = new Map();
    for (const e of entries) {
        const live = e.names.filter((n) => !stubs.includes(n));
        if (!live.length) continue;
        if (!groups.has(e.group)) groups.set(e.group, []);
        groups.get(e.group).push({ ...e, names: live });
    }
    const lines = [];
    lines.push(
        `This catalog is generated from the \`match cmd\` of \`route_command\` and from \`is_stub_command\`: ${names.length} commands the host handles, and ${stubs.length} names it accepts and ignores. The note is the comment directly above the command's arm in the code. **Handler** is the first function the arm calls, leaving out library calls and precondition checks: where an arm works in several places, read the arm. Argument and return shapes are not listed: they are in the handler.`,
        "",
        "**Runs** says where the handler works: `inline` on the IPC request task, `async` when the arm awaits, `blocking` when it hops to a blocking thread (`spawn_blocking`). **Args** says whether the arm passes the request's arguments on.",
    );
    for (const [group, items] of groups) {
        lines.push("", `#### ${cell(group)}`, "", "| Command | Handler | Runs | Args | Note |", "|---------|---------|------|------|------|");
        for (const e of items) {
            const note = e.note.length > NOTE_MAX ? `${e.note.slice(0, NOTE_MAX - 1).trimEnd()}…` : e.note;
            const handler = e.handler === "in the arm" ? e.handler : `\`${e.handler}\``;
            lines.push(`| ${e.names.map((n) => `\`${n}\``).join(", ")} | ${handler} | ${e.runs} | ${e.args ? "yes" : "—"} | ${cell(note)} |`);
        }
    }
    if (stubs.length) {
        lines.push(
            "",
            "#### Stubs",
            "",
            "Accepted and answered with null, so a frontend that still calls them does not error. They do nothing (`crates/cef/src/commands/stubs.rs`).",
            "",
            stubs.map((s) => `\`${s}\``).join(", "),
        );
    }
    return lines.join("\n");
}

/** The generated block (markers included) for the code under `root`, or `{ error }`. */
export function generate(root) {
    const ipc = join(root, IPC_RS);
    const stubsPath = join(root, STUBS_RS);
    if (!existsSync(ipc)) return { error: `${IPC_RS} not found under ${root}` };
    const entries = routeCommandEntries(readFileSync(ipc, "utf8"));
    if (!entries.length) return { error: `no \`match cmd\` arms found in route_command of ${IPC_RS}` };
    const stubs = existsSync(stubsPath) ? stubNames(readFileSync(stubsPath, "utf8")) : [];
    return { block: `${BEGIN}\n\n${renderCatalog(entries, stubs)}\n\n${END}` };
}

/** `page` with the text between the markers (markers included) replaced by `block`, or `{ error }`. */
export function splice(page, block) {
    const a = page.indexOf(BEGIN);
    const b = page.indexOf(END);
    if (a < 0 || b < a) return { error: "the page has no ipc-catalog begin/end markers (see the header of scripts/gen-ipc-catalog.mjs)" };
    return { page: page.slice(0, a) + block + page.slice(b + END.length) };
}

function main(argv) {
    const arg = (name) => {
        const at = argv.indexOf(name);
        return at >= 0 ? argv[at + 1] : undefined;
    };
    const root = resolve(arg("--code") ?? ".");
    const pagePath = arg("--page");
    const g = generate(root);
    if (g.error) {
        console.error(`gen-ipc-catalog: ${g.error}`);
        return 2;
    }
    if (!pagePath) {
        console.log(g.block);
        return 0;
    }
    const page = readFileSync(pagePath, "utf8");
    const s = splice(page, g.block);
    if (s.error) {
        console.error(`gen-ipc-catalog: ${pagePath}: ${s.error}`);
        return 2;
    }
    if (argv.includes("--write")) {
        if (s.page !== page) writeFileSync(pagePath, s.page);
        console.log(`gen-ipc-catalog: ${pagePath} ${s.page === page ? "already current" : "rewritten"}.`);
        return 0;
    }
    if (s.page === page) {
        console.log("gen-ipc-catalog: ok. The host command catalog matches route_command.");
        return 0;
    }
    console.error(
        `gen-ipc-catalog: ${pagePath} does not match route_command in ${IPC_RS}.\n` +
            `  A command was added, removed or renamed, or its handler or comment changed. Regenerate the block:\n` +
            `  node scripts/gen-ipc-catalog.mjs --code ${arg("--code") ?? "."} --page ${pagePath} --write`,
    );
    return 1;
}

if (isMain(import.meta.url)) process.exitCode = main(process.argv.slice(2));
