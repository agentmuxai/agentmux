// Generates the frontend's map of typed broker events from srv's own list of them
// (docs/specs/SPEC_TYPED_EVENT_PAYLOADS_2026_10_13.md).
//
//   frontend/types/rpc/event-schema.json   each typed event's wire name and payload type, written
//                                          by srv's `export_bindings_event_schema` test from
//                                          crates/srv/src/backend/mps_events.rs
//   -> frontend/app/store/mps-events.generated.ts   `MuxEventPayloads`, which `onMuxEvent` reads
//
// It also refuses a typed event subscribed the untyped way: `muxEventSubscribe` with one as its
// eventType hands the handler `any` data, so it must go through `onMuxEvent` instead.
//
// Usage:
//   node scripts/gen-mux-events.mjs           write mps-events.generated.ts
//   node scripts/gen-mux-events.mjs --check   fail if it's stale, or a typed event is subscribed untyped (CI)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA = join(ROOT, "frontend/types/rpc/event-schema.json");
const OUT = join(ROOT, "frontend/app/store/mps-events.generated.ts");
const NAMES = join(ROOT, "frontend/app/store/mps-events.ts");

/** The generated file's source for `rows` (event-schema.json). */
export function renderEvents(rows) {
    const imports = new Set(rows.flatMap((r) => r.payloadTs.imports));
    const fixed = rows.filter((r) => !r.perId);
    const perId = rows.filter((r) => r.perId);
    const noPayload = (r) => r.payloadTs.name === "null";
    return [
        "// Copyright 2026, AgentMux Corp.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// @generated by scripts/gen-mux-events.mjs from frontend/types/rpc/event-schema.json (srv's",
        "// crates/srv/src/backend/mps_events.rs). DO NOT EDIT: declare the event there, then run",
        "// `cargo test -p agentmux-srv export_bindings` and `node scripts/gen-mux-events.mjs`.",
        "",
        ...[...imports].sort().map((n) => `import type { ${n} } from "@/types/rpc/${n}";`),
        "",
        "/** Each typed broker event's payload, by its wire name. An event sent under a name per id",
        " *  (`agent:memory:changed:<agent id>`) is keyed by its prefix and any id. Subscribe with `onMuxEvent`. */",
        "export type MuxEventPayloads = {",
        ...fixed.map((r) => `    ${JSON.stringify(r.event)}: ${r.payloadTs.name};`),
        ...perId.map((r) => `    [event: \`${r.event}\${string}\`]: ${r.payloadTs.name};`),
        "};",
        "",
        "/** The typed events' wire names, apart from the per-id ones. */",
        `export const TYPED_MUX_EVENTS = [${fixed.map((r) => JSON.stringify(r.event)).join(", ")}] as const;`,
        "",
        "/** Whether a typed event carries no payload: srv sends it with no `data`. */",
        "export function isNoPayloadMuxEvent(eventType: string): boolean {",
        "    return NO_PAYLOAD_MUX_EVENTS.has(eventType) || NO_PAYLOAD_PER_ID_PREFIXES.some((p) => eventType.startsWith(p));",
        "}",
        "",
        `const NO_PAYLOAD_MUX_EVENTS: ReadonlySet<string> = new Set([${fixed.filter(noPayload).map((r) => JSON.stringify(r.event)).join(", ")}]);`,
        "",
        `const NO_PAYLOAD_PER_ID_PREFIXES: readonly string[] = [${perId.filter(noPayload).map((r) => JSON.stringify(r.event)).join(", ")}];`,
        "",
    ].join("\n");
}

/** `WpsEvent.<Key>` -> wire name, from mps-events.ts. */
export function wpsNames(source) {
    return new Map([...source.matchAll(/^\s*(\w+):\s*"([^"]+)"/gm)].map((m) => [m[1], m[2]]));
}

const parsed = new Map();

function sourceFile(path, text) {
    let sf = parsed.get(text);
    if (!sf) {
        const kind = path.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
        sf = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, kind);
        parsed.set(text, sf);
    }
    return sf;
}

/** Whether `at` in the source at `path` falls inside a comment. TypeScript parses the file, so a
 *  `//` or `/*` inside a string, a template or a regex literal is not taken for one: a comment is
 *  what lies in a token's leading trivia. */
function inComment(path, text, at) {
    const sf = sourceFile(path, text);
    for (let node = sf; ; ) {
        const child = node.getChildren(sf).find((c) => c.pos <= at && at < c.end);
        if (!child) return at < node.getStart(sf);
        // A doc comment is parsed into JSDoc nodes of its own.
        if (child.kind >= ts.SyntaxKind.FirstJSDocNode && child.kind <= ts.SyntaxKind.LastJSDocNode) return true;
        node = child;
    }
}

/** `onMuxEvent` handlers still written against the event rather than its payload: the first
 *  parameter typed `any`, `unknown` or `MuxEvent`, or read as `<param>.data`. Such a handler
 *  gets the payload itself, so `event.data` is silently `undefined`, and `tsc` can't tell when
 *  the parameter is `any`. No typed payload has a top-level `data` field; if one ever does, its
 *  handlers name the read differently (`const { data } = payload`). */
export function eventShapedHandlers(sources) {
    const errors = [];
    for (const [path, text] of sources) {
        if (!text.includes("onMuxEvent(")) continue;
        const sf = sourceFile(path, text);
        const visit = (node) => {
            if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === "onMuxEvent") {
                const handler = node.arguments[1];
                const param = handler && (ts.isArrowFunction(handler) || ts.isFunctionExpression(handler)) ? handler.parameters[0] : undefined;
                if (param) {
                    const type = param.type?.getText(sf).trim();
                    let readsData = false;
                    if (ts.isIdentifier(param.name)) {
                        const name = param.name.text;
                        // `event.data`, also through a cast or parentheses: `(event as any)?.data`.
                        const receiver = (e) =>
                            ts.isParenthesizedExpression(e) || ts.isAsExpression(e) || ts.isTypeAssertionExpression(e) || ts.isNonNullExpression(e) || ts.isSatisfiesExpression(e)
                                ? receiver(e.expression)
                                : e;
                        const walk = (n) => {
                            if (ts.isPropertyAccessExpression(n) && n.name.text === "data") {
                                const r = receiver(n.expression);
                                if (ts.isIdentifier(r) && r.text === name) readsData = true;
                            }
                            ts.forEachChild(n, walk);
                        };
                        walk(handler.body);
                    }
                    if ((type && /^(any|unknown|MuxEvent)$/.test(type)) || readsData) {
                        const line = sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;
                        errors.push(`${path}:${line}: onMuxEvent's handler gets the payload itself, typed; take it as (data) => …, not the event`);
                    }
                }
            }
            ts.forEachChild(node, visit);
        };
        visit(sf);
    }
    return errors;
}

/** Event-name constants declared in any source (`const EVENT_AGENT_SHUTDOWN = "agent:shutdown"`,
 *  or `= WpsEvent.X`), by name. */
function eventConsts(sources, wps) {
    const consts = new Map();
    for (const [, text] of sources) {
        for (const m of text.matchAll(/\bconst\s+([A-Z][A-Z0-9_]*)\s*(?::\s*string\s*)?=\s*(?:"([^"]+)"|WpsEvent\.(\w+))/g)) {
            const name = m[2] ?? wps.get(m[3]);
            if (name) consts.set(m[1], name);
        }
    }
    return consts;
}

/** `EventReadHistoryCommand` reads of a typed event outside `mps-history.ts`'s
 *  `readMuxEventHistory`, which returns the stored payloads typed. The event is named in the
 *  call's `event:` field as `WpsEvent.<Key>`, a literal, a constant, or a per-id template. */
export function untypedHistoryReads(sources, typed, wps, perIdPrefixes = new Set()) {
    const errors = [];
    const consts = eventConsts(sources, wps);
    const nameOf = (e) => {
        if (ts.isPropertyAccessExpression(e) && ts.isIdentifier(e.expression) && e.expression.text === "WpsEvent") return wps.get(e.name.text);
        if (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e)) return e.text;
        if (ts.isIdentifier(e)) return consts.get(e.text);
        if (ts.isTemplateExpression(e) && perIdPrefixes.has(e.head.text)) return `${e.head.text}<id>`;
        return undefined;
    };
    for (const [path, text] of sources) {
        if (path.endsWith("app/store/mps-history.ts") || !text.includes("EventReadHistoryCommand")) continue;
        const sf = sourceFile(path, text);
        const visit = (node) => {
            if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression) && node.expression.name.text === "EventReadHistoryCommand") {
                // Allowed only when the event is named inline and isn't typed. A request built
                // elsewhere, or an event this can't resolve, is refused: it may be a typed one.
                const line = sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;
                const request = node.arguments.find((a) => ts.isObjectLiteralExpression(a));
                const prop = request?.properties.find((p) => ts.isPropertyAssignment(p) && p.name.getText(sf) === "event");
                const name = prop && nameOf(prop.initializer);
                if (!name) {
                    errors.push(`${path}:${line}: EventReadHistoryCommand without an event named inline (\`event: WpsEvent.X\`, a literal or a constant); a typed event's history is read with readMuxEventHistory (app/store/mps-history.ts)`);
                } else if (typed.has(name) || name.endsWith("<id>")) {
                    errors.push(`${path}:${line}: "${name}" has a typed payload; read its history with readMuxEventHistory (app/store/mps-history.ts), not EventReadHistoryCommand`);
                }
            }
            ts.forEachChild(node, visit);
        };
        visit(sf);
    }
    return errors;
}

/** Where a typed event is subscribed with `muxEventSubscribe` instead of `onMuxEvent`, in
 *  `sources` ([path, text]). A subscription names its event as `WpsEvent.<Key>` or a literal, or a
 *  per-id event as a template literal starting with one of `perIdPrefixes`. */
export function untypedSubscriptions(sources, typed, wps, perIdPrefixes = new Set()) {
    const errors = [];
    // A subscription can also name its event through a string constant of its own.
    const consts = eventConsts(sources, wps);
    for (const [path, text] of sources) {
        for (const m of text.matchAll(/eventType:\s*(?:WpsEvent\.(\w+)|"([^"]+)"|([A-Z][A-Z0-9_]*)\b)/g)) {
            const name = m[1] ? wps.get(m[1]) : m[2] ?? consts.get(m[3]);
            if (!name || !typed.has(name)) continue;
            const line = text.slice(0, m.index).split("\n").length;
            errors.push(`${path}:${line}: "${name}" has a typed payload; subscribe with onMuxEvent(WpsEvent.${m[1] ?? "…"}, (data) => …), not muxEventSubscribe`);
        }
        for (const m of text.matchAll(/eventType:\s*`([^`$]*)\$\{/g)) {
            if (!perIdPrefixes.has(m[1])) continue;
            const line = text.slice(0, m.index).split("\n").length;
            errors.push(`${path}:${line}: "${m[1]}<id>" has a typed payload; subscribe with onMuxEvent(\`${m[1]}\${id}\`, (data) => …), not muxEventSubscribe`);
        }
        // Any other use of a typed event's WpsEvent name, such as a list mapped into
        // `muxEventSubscribe({ eventType, … })`, hides how it is subscribed. Allowed: onMuxEvent's
        // first argument, readMuxEventHistory's, `eventType:` (checked above), an RPC's `event:` field
        // (EventReadHistoryCommand's is checked by untypedHistoryReads), and a named constant.
        for (const m of text.matchAll(/WpsEvent\.(\w+)\b/g)) {
            const name = wps.get(m[1]);
            if (!name || !typed.has(name)) continue;
            if (/(?:onMuxEvent\(|readMuxEventHistory\(|eventType:|\bevent:|\bconst\s+\w+\s*(?::\s*string\s*)?=)\s*$/.test(text.slice(Math.max(0, m.index - 60), m.index))) continue;
            // A comment naming the event subscribes nothing.
            if (inComment(path, text, m.index)) continue;
            const line = text.slice(0, m.index).split("\n").length;
            errors.push(`${path}:${line}: WpsEvent.${m[1]} has a typed payload; pass it straight to onMuxEvent(WpsEvent.${m[1]}, (data) => …)`);
        }
    }
    return errors;
}

function frontendSources() {
    const out = [];
    const walk = (dir) => {
        for (const e of readdirSync(dir, { withFileTypes: true })) {
            const p = join(dir, e.name);
            if (e.isDirectory()) { if (e.name !== "node_modules") walk(p); }
            else if (/\.tsx?$/.test(e.name) && !/\.(test|spec)\.tsx?$/.test(e.name) && p !== OUT) out.push([relative(ROOT, p).replace(/\\/g, "/"), readFileSync(p, "utf8")]);
        }
    };
    walk(join(ROOT, "frontend"));
    return out;
}

async function main() {
    const check = process.argv.includes("--check");
    const rows = JSON.parse(readFileSync(SCHEMA, "utf8"));
    const wps = wpsNames(readFileSync(NAMES, "utf8"));
    const errors = [];
    const known = new Set(wps.values());
    const fixed = rows.filter((r) => !r.perId);
    for (const r of fixed) if (!known.has(r.event)) errors.push(`"${r.event}" is typed in srv but has no WpsEvent name in frontend/app/store/mps-events.ts`);
    const perIdPrefixes = new Set(rows.filter((r) => r.perId).map((r) => r.event));
    const sources = frontendSources();
    errors.push(...untypedSubscriptions(sources, new Set(fixed.map((r) => r.event)), wps, perIdPrefixes));
    errors.push(...eventShapedHandlers(sources));
    errors.push(...untypedHistoryReads(sources, new Set(fixed.map((r) => r.event)), wps, perIdPrefixes));
    if (errors.length) {
        console.error(`gen-mux-events: ${errors.length} problem(s):\n${errors.map((e) => `  - ${e}`).join("\n")}`);
        process.exit(1);
    }
    const prettier = await import("prettier");
    const config = (await prettier.resolveConfig(OUT)) ?? {};
    const source = await prettier.format(renderEvents(rows), { ...config, filepath: OUT });
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
    if (check) {
        if (current !== source) {
            console.error("gen-mux-events: frontend/app/store/mps-events.generated.ts is stale. Run: node scripts/gen-mux-events.mjs");
            process.exit(1);
        }
        console.log(`gen-mux-events: ok (${rows.length} typed event(s), all subscribed through onMuxEvent)`);
        return;
    }
    if (current === source) console.log(`gen-mux-events: unchanged (${rows.length} typed event(s))`);
    else {
        writeFileSync(OUT, source);
        console.log(`gen-mux-events: wrote ${rows.length} typed event(s) to frontend/app/store/mps-events.generated.ts`);
    }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
