// Generates the frontend's map of typed broker events from srv's own list of them
// (docs/specs/SPEC_TYPED_EVENT_PAYLOADS_2026_10_13.md).
//
//   frontend/types/rpc/event-schema.json   each typed event's wire name and payload type, written
//                                          by srv's `export_bindings_event_schema` test from
//                                          crates/srv/src/backend/mps_events.rs
//   -> frontend/app/store/mps-events.generated.ts   `MuxEventPayloads`, which `onMuxEvent` reads
//
// It also refuses a typed event subscribed the untyped way: `muxEventSubscribe` with one as its
// eventType hands the handler `any` data, so it must go through `onMuxEvent` instead.
//
// Usage:
//   node scripts/gen-mux-events.mjs           write mps-events.generated.ts
//   node scripts/gen-mux-events.mjs --check   fail if it's stale, or a typed event is subscribed untyped (CI)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA = join(ROOT, "frontend/types/rpc/event-schema.json");
const OUT = join(ROOT, "frontend/app/store/mps-events.generated.ts");
const NAMES = join(ROOT, "frontend/app/store/mps-events.ts");

/** The generated file's source for `rows` (event-schema.json). */
export function renderEvents(rows) {
    const imports = new Set(rows.flatMap((r) => r.payloadTs.imports));
    return [
        "// Copyright 2026, AgentMux Corp.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// @generated by scripts/gen-mux-events.mjs from frontend/types/rpc/event-schema.json (srv's",
        "// crates/srv/src/backend/mps_events.rs). DO NOT EDIT: declare the event there, then run",
        "// `cargo test -p agentmux-srv export_bindings` and `node scripts/gen-mux-events.mjs`.",
        "",
        ...[...imports].sort().map((n) => `import type { ${n} } from "@/types/rpc/${n}";`),
        "",
        "/** Each typed broker event's payload, by its wire name. Subscribe with `onMuxEvent`. */",
        "export type MuxEventPayloads = {",
        ...rows.map((r) => `    ${JSON.stringify(r.event)}: ${r.payloadTs.name};`),
        "};",
        "",
        "/** The typed events' wire names. */",
        `export const TYPED_MUX_EVENTS = [${rows.map((r) => JSON.stringify(r.event)).join(", ")}] as const;`,
        "",
        "/** The typed events that carry no payload: srv sends them with no `data`. */",
        `export const NO_PAYLOAD_MUX_EVENTS: ReadonlySet<string> = new Set([${rows.filter((r) => r.payloadTs.name === "null").map((r) => JSON.stringify(r.event)).join(", ")}]);`,
        "",
    ].join("\n");
}

/** `WpsEvent.<Key>` -> wire name, from mps-events.ts. */
export function wpsNames(source) {
    return new Map([...source.matchAll(/^\s*(\w+):\s*"([^"]+)"/gm)].map((m) => [m[1], m[2]]));
}

/** Where a typed event is subscribed with `muxEventSubscribe` instead of `onMuxEvent`, in
 *  `sources` ([path, text]). A subscription names its event as `WpsEvent.<Key>` or a literal. */
export function untypedSubscriptions(sources, typed, wps) {
    const errors = [];
    // A subscription can also name its event through a string constant of its own
    // (`const EVENT_AGENT_SHUTDOWN = "agent:shutdown"`), declared in any source.
    const consts = new Map();
    for (const [, text] of sources) {
        for (const m of text.matchAll(/\bconst\s+([A-Z][A-Z0-9_]*)\s*(?::\s*string\s*)?=\s*(?:"([^"]+)"|WpsEvent\.(\w+))/g)) {
            const name = m[2] ?? wps.get(m[3]);
            if (name) consts.set(m[1], name);
        }
    }
    for (const [path, text] of sources) {
        for (const m of text.matchAll(/eventType:\s*(?:WpsEvent\.(\w+)|"([^"]+)"|([A-Z][A-Z0-9_]*)\b)/g)) {
            const name = m[1] ? wps.get(m[1]) : m[2] ?? consts.get(m[3]);
            if (!name || !typed.has(name)) continue;
            const line = text.slice(0, m.index).split("\n").length;
            errors.push(`${path}:${line}: "${name}" has a typed payload; subscribe with onMuxEvent(WpsEvent.${m[1] ?? "…"}, (data) => …), not muxEventSubscribe`);
        }
    }
    return errors;
}

function frontendSources() {
    const out = [];
    const walk = (dir) => {
        for (const e of readdirSync(dir, { withFileTypes: true })) {
            const p = join(dir, e.name);
            if (e.isDirectory()) { if (e.name !== "node_modules") walk(p); }
            else if (/\.tsx?$/.test(e.name) && !/\.(test|spec)\.tsx?$/.test(e.name) && p !== OUT) out.push([relative(ROOT, p).replace(/\\/g, "/"), readFileSync(p, "utf8")]);
        }
    };
    walk(join(ROOT, "frontend"));
    return out;
}

async function main() {
    const check = process.argv.includes("--check");
    const rows = JSON.parse(readFileSync(SCHEMA, "utf8"));
    const wps = wpsNames(readFileSync(NAMES, "utf8"));
    const errors = [];
    const known = new Set(wps.values());
    for (const r of rows) if (!known.has(r.event)) errors.push(`"${r.event}" is typed in srv but has no WpsEvent name in frontend/app/store/mps-events.ts`);
    errors.push(...untypedSubscriptions(frontendSources(), new Set(rows.map((r) => r.event)), wps));
    if (errors.length) {
        console.error(`gen-mux-events: ${errors.length} problem(s):\n${errors.map((e) => `  - ${e}`).join("\n")}`);
        process.exit(1);
    }
    const prettier = await import("prettier");
    const config = (await prettier.resolveConfig(OUT)) ?? {};
    const source = await prettier.format(renderEvents(rows), { ...config, filepath: OUT });
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
    if (check) {
        if (current !== source) {
            console.error("gen-mux-events: frontend/app/store/mps-events.generated.ts is stale. Run: node scripts/gen-mux-events.mjs");
            process.exit(1);
        }
        console.log(`gen-mux-events: ok (${rows.length} typed event(s), all subscribed through onMuxEvent)`);
        return;
    }
    if (current === source) console.log(`gen-mux-events: unchanged (${rows.length} typed event(s))`);
    else {
        writeFileSync(OUT, source);
        console.log(`gen-mux-events: wrote ${rows.length} typed event(s) to frontend/app/store/mps-events.generated.ts`);
    }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
