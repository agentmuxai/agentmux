// Generates the aliases a pane's backdrop has to re-resolve
// (docs/specs/SPEC_PANE_BACKGROUND_THEMES_2026_11_15.md §7.3):
//
//   frontend/app/theme.scss + frontend/app/backdrop/mapped-tokens.json
//   -> frontend/app/backdrop/_aliases.scss
//
// A custom property that is `var(--main-text-color)` resolves where it is declared: an alias set on `:root` reads
// `:root`'s `--main-text-color`, so a pane that only overrides the base tokens does not re-colour it. Every alias
// that depends, directly or through other aliases, on a token the pane scope re-points (mapped-tokens.json) is
// declared again on `[data-backdrop]` with its `:root` value, so it resolves at the pane against the pane's tokens.
//
// Usage:
//   node scripts/gen-backdrop-aliases.mjs           write _aliases.scss
//   node scripts/gen-backdrop-aliases.mjs --check   fail if it is stale (CI)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { declarations } from "./check-ui-primitives.mjs";
import { isMain } from "./lib/is-main.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const THEME = join(ROOT, "frontend/app/theme.scss");
const MAPPED = join(ROOT, "frontend/app/backdrop/mapped-tokens.json");
const OUT = join(ROOT, "frontend/app/backdrop/_aliases.scss");

/** The custom properties `theme.scss` sets on `:root` itself (alone or in a list), outside any at-rule, in file order; a later one wins. */
export function rootDefaults(scss) {
    const onRoot = (selector) => selector.split(",").some((s) => s.trim() === ":root");
    const tokens = new Map();
    for (const d of declarations(scss)) {
        if (!d.property.startsWith("--") || d.conditional || !onRoot(d.selector)) continue;
        tokens.set(d.property, d.value.replace(/\s*!important$/, ""));
    }
    return tokens;
}

/** The custom properties a value reads with `var(--x …)`. */
export const varsIn = (value) => [...value.matchAll(/var\(\s*(--[\w-]+)/g)].map((m) => m[1]);

/** The mapped tokens, flattened to their names. */
export const mappedNames = (mapped) => [...Object.keys(mapped.surface), ...Object.keys(mapped.ink), ...mapped.channels];

/**
 * The tokens that depend, directly or through one another, on a mapped token, in the order `defaults` has them.
 * A mapped token is not one of them: the pane scope sets it.
 */
export function dependentAliases(defaults, mapped) {
    const mappedSet = new Set(mappedNames(mapped));
    // Tokens kept at the window's value inside a pane on purpose (`windowLevel`): never re-resolved, and nothing reads a mapped token through them.
    const windowLevel = new Set(mapped.windowLevel ?? []);
    const dependent = new Set();
    let grew = true;
    while (grew) {
        grew = false;
        for (const [name, value] of defaults) {
            if (mappedSet.has(name) || dependent.has(name) || windowLevel.has(name)) continue;
            if (varsIn(value).some((v) => mappedSet.has(v) || dependent.has(v))) {
                dependent.add(name);
                grew = true;
            }
        }
    }
    return [...defaults.keys()].filter((name) => dependent.has(name));
}

/** The generated file's source. */
export function renderAliases(defaults, mapped) {
    const names = dependentAliases(defaults, mapped);
    return [
        "// Copyright 2026, AgentMux Corp.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// @generated by scripts/gen-backdrop-aliases.mjs from frontend/app/theme.scss and mapped-tokens.json. Do not edit.",
        "//",
        "// Each alias below depends, directly or through another, on a token a pane's backdrop re-points. It is set again on",
        "// the pane's own element, with its `:root` value, so `var(--main-text-color)` in it resolves against the pane.",
        "// A light theme's own override of an alias does not reach a pane: the pane's ink already carries its polarity.",
        "",
        "/* stylelint-disable color-no-hex -- the values are theme.scss's own, copied */",
        "[data-backdrop] {",
        ...names.map((name) => `    ${name}: ${defaults.get(name)};`),
        "}",
        "/* stylelint-enable color-no-hex */",
        "",
    ].join("\n");
}

/** What `_aliases.scss` should say now. */
export function expected() {
    return renderAliases(rootDefaults(readFileSync(THEME, "utf8")), JSON.parse(readFileSync(MAPPED, "utf8")));
}

if (isMain(import.meta.url)) {
    const want = expected();
    if (process.argv.includes("--check")) {
        const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
        if (have !== want) {
            console.error("frontend/app/backdrop/_aliases.scss is stale: run `node scripts/gen-backdrop-aliases.mjs` and commit it.");
            process.exit(1);
        }
        console.log("OK: _aliases.scss is up to date");
    } else {
        writeFileSync(OUT, want);
        console.log(`wrote ${OUT.slice(ROOT.length + 1)}`);
    }
}
