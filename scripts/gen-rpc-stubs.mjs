// Generates the frontend's RPC command stubs from srv's own record of them.
//
//   frontend/types/rpc/rpc-schema.json      every typed command's request and response, as
//                                           TypeScript, written by srv's
//                                           `export_bindings_rpc_schema` test (ts-rs names)
//   frontend/app/store/rpc-api/generated-manifest.json
//                                           which commands are generated, under which method
//                                           name, and the few call details the schema can't
//                                           say (what a no-argument call sends, a timeout)
//   -> frontend/app/store/rpc-api/generated.ts   `GeneratedApi`, spread into `RpcApi`
//
// A command moves from hand-written to generated by adding it to the manifest and deleting its
// hand-written method; the method keeps its name, so no caller changes. This is
// docs/specs/SPEC_RPC_BINDINGS_CODEGEN_2026_09_07.md §3.2, built on the RpcSchema registry
// (crates/srv/src/backend/rpc/schema.rs).
//
// Usage:
//   node scripts/gen-rpc-stubs.mjs           write generated.ts
//   node scripts/gen-rpc-stubs.mjs --check   fail if generated.ts isn't what this would write (CI)
//
// It refuses to write anything rather than emit a stub it can't vouch for: a manifest command
// srv doesn't register as typed, a type name that is neither a generated import nor a
// hand-written global, a duplicate.
//
// Every RPC stub is generated, and nothing else may call srv's commands: a hand-written stub
// in rpc-api/, an `RpcApi` that is anything but `GeneratedApi`, or a raw
// `client.rpcCall("<command>", …)` outside generated.ts fails it too (generatedOnlyProblems).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA = join(ROOT, "frontend/types/rpc/rpc-schema.json");
const RPC_TYPES = join(ROOT, "frontend/types/rpc");
const API_DIR = join(ROOT, "frontend/app/store/rpc-api");
const MANIFEST = join(API_DIR, "generated-manifest.json");
const OUT = join(API_DIR, "generated.ts");
const AMBIENT_FILES = [join(ROOT, "frontend/types/srv-types.d.ts"), join(ROOT, "frontend/types/custom.d.ts")];

/** Request types that mean "no argument": the stub takes no data parameter. */
const NO_ARGS = new Set(["NoArgsReq", "NoArgsReq | null", "NotifyNoArgs", "NotifyNoArgs | null", "null"]);
/** Built-in names a type expression may use without an import. */
const BUILTIN = new Set(["Array", "Record", "Partial", "Promise", "Omit", "Pick"]);

/** The TypeScript a schema type name becomes in a stub. */
export function tsOf(name) {
    if (name === "JsonValue") return "any"; // what the hand-written stubs use for raw JSON
    if (name === "JsonValue | null") return "any";
    return name;
}

/** A raw-JSON (serde_json::Value) request or response that the manifest gives a precise
 *  TypeScript type, as its hand-written stub had (`dataType` / `returns`). Allowed only where
 *  the schema really says JsonValue: anywhere else the Rust type is the truth. */
function overridden(entry, side, schemaName) {
    const key = side === "data" ? "dataType" : "returns";
    if (entry[key] === undefined) return null;
    if (!/^JsonValue( | null)?$/.test(schemaName))
        throw new Error(`${entry.command}: "${key}" overrides only a serde_json::Value ${side === "data" ? "request" : "response"}; this one is ${schemaName}`);
    return entry[key];
}

/** `X` with `entry.optionalFields` made optional: fields srv defaults (`#[serde(default)]`) on a
 *  non-Option field, which ts-rs can't mark `#[ts(optional)]` itself. The manifest names them and
 *  a Rust test proves srv accepts the request without them; `generate` checks they exist. */
function withOptionalFields(entry, baseType) {
    if (!/^[A-Z]\w*$/.test(baseType)) throw new Error(`${entry.command}: "optionalFields" needs a single named request type, not ${baseType}`);
    const keys = entry.optionalFields.map((k) => JSON.stringify(k)).join(" | ");
    return `Omit<${baseType}, ${keys}> & Partial<Pick<${baseType}, ${keys}>>`;
}

/** Whether the stub takes no data parameter. */
const takesNoData = (entry, req) => NO_ARGS.has(req) || entry.send === "{}" || entry.send === "null";

/** One stub's source, from its manifest entry and schema row. Exported for the tests. */
export function renderStub(entry, row) {
    const req = row.requestTs.name;
    const resp = row.responseTs.name;
    const ret = overridden(entry, "returns", resp) ?? (resp === "null" ? "void" : tsOf(resp));
    const opts = entry.opts ?? "opts";
    const lines = [`    // command "${entry.command}"`];
    const optional = req.endsWith(" | null");
    // No data parameter: a no-argument command, or a request the stub always sends empty
    // (`send` "{}" for an Option or a struct whose fields all default, "null" for an Option),
    // so existing `(client, opts)` calls keep binding opts.
    if (takesNoData(entry, req)) {
        // A Rust `()` request (ts-rs: `null`) deserializes only from JSON null, so it sends null;
        // an empty struct (`NoArgsReq`) only from `{}`; `Option<NoArgsReq>` takes either.
        const unit = req === "null";
        const send = entry.send ?? (unit ? "null" : "{}");
        // serde_json::Value (JsonValue) takes anything, null included.
        if (send === "null" && !unit && !optional && !NO_ARGS.has(req) && req !== "JsonValue") throw new Error(`${entry.command}: "send": "null" needs an Option or () request; ${req} doesn't deserialize from null`);
        if (send !== "{}" && send !== "null") throw new Error(`${entry.command}: "send" for a no-argument command is "{}" or "null", not ${send}`);
        if (unit && send !== "null") throw new Error(`${entry.command}: its Rust request is (), which only deserializes from null, so "send" must be "null"`);
        if (/^(NoArgsReq|NotifyNoArgs)$/.test(req) && send !== "{}") throw new Error(`${entry.command}: its Rust request is ${req}, an empty struct, which only deserializes from {}, so "send" must be "{}"`);
        lines.push(`    ${entry.method}(client: RpcClient, opts?: RpcOpts): Promise<${ret}> {`);
        lines.push(`        return client.rpcCall(${JSON.stringify(entry.command)}, ${send}, ${opts});`);
    } else {
        const baseType = overridden(entry, "data", req) ?? tsOf(optional ? req.slice(0, -" | null".length) : req);
        const dataType = entry.optionalFields ? withOptionalFields(entry, baseType) : baseType;
        const send = entry.send ?? "data";
        if (send !== "data" && send !== "data ?? {}") throw new Error(`${entry.command}: "send" is "data", "data ?? {}", "{}" or "null", not ${send}`);
        // `data ?? {}` makes the parameter optional even for a non-Option request: the struct
        // must then deserialize from `{}` (every field defaulted), which the manifest entry
        // vouches for.
        const param = optional ? `data?: ${dataType} | null` : send === "data ?? {}" ? `data?: ${dataType}` : `data: ${dataType}`;
        lines.push(`    ${entry.method}(client: RpcClient, ${param}, opts?: RpcOpts): Promise<${ret}> {`);
        lines.push(`        return client.rpcCall(${JSON.stringify(entry.command)}, ${send}, ${opts});`);
    }
    lines.push("    },");
    return lines.join("\n");
}

/** The type names a stub uses, so each can be checked and imported. */
export function namesUsed(entry, row) {
    const exprs = [overridden(entry, "returns", row.responseTs.name) ?? row.responseTs.name];
    if (!takesNoData(entry, row.requestTs.name)) exprs.push(overridden(entry, "data", row.requestTs.name) ?? row.requestTs.name);
    const names = new Set();
    // An override may name a frontend module's type as `import("@/path").Type`: tsc resolves
    // that itself, so it is neither an import to add nor a global to check.
    const unimported = (e) => tsOf(e).replace(/import\("[^"]+"\)\.\w+/g, "");
    for (const e of exprs) for (const m of unimported(e).matchAll(/\b[A-Z][A-Za-z0-9_]*\b/g)) if (!BUILTIN.has(m[0])) names.add(m[0]);
    return names;
}

function ambientNames() {
    const names = new Set();
    for (const f of AMBIENT_FILES) for (const m of readFileSync(f, "utf8").matchAll(/^\s*(?:type|interface)\s+([A-Za-z_]\w*)/gm)) names.add(m[1]);
    return names;
}

/** Every `Method(client: RpcClient` in the hand-written rpc-api files, by method name. */
function handWritten() {
    const where = new Map();
    for (const f of readdirSync(API_DIR)) {
        if (!f.endsWith(".ts") || f === "generated.ts" || f === "index.ts") continue;
        for (const m of readFileSync(join(API_DIR, f), "utf8").matchAll(/(\w+)\s*\(\s*client:\s*RpcClient/g)) where.set(m[1], f);
    }
    return where;
}

export function generate({ schema, manifest, ambient, generatedTypes, hand, fieldsOf = () => null }) {
    const rows = new Map(schema.map((r) => [r.command, r]));
    const errors = [];
    const seenCmd = new Set();
    const seenMethod = new Set();
    const imports = new Set();
    const stubs = [];
    for (const entry of manifest.stubs) {
        const { command, method } = entry;
        if (!command || !method) { errors.push(`manifest entry without command or method: ${JSON.stringify(entry)}`); continue; }
        if (seenCmd.has(command)) errors.push(`${command}: listed twice`);
        if (seenMethod.has(method)) errors.push(`${method}: two commands generate it`);
        seenCmd.add(command);
        seenMethod.add(method);
        if (hand.has(method)) errors.push(`${method}: still hand-written in rpc-api/${hand.get(method)}; delete it there`);
        const row = rows.get(command);
        if (!row) { errors.push(`${command}: srv doesn't register it with register_typed, so there are no types to generate from`); continue; }
        if (!row.requestTs || !row.responseTs) { errors.push(`${command}: the schema has no TypeScript for it`); continue; }
        try {
            if (entry.optionalFields) {
                if (takesNoData(entry, row.requestTs.name)) throw new Error(`${command}: "optionalFields" on a command that takes no data`);
                const t = row.requestTs.name.replace(/ \| null$/, "");
                const fields = fieldsOf(t);
                if (!fields) throw new Error(`${command}: "optionalFields" needs a generated request type; ${t} has no frontend/types/rpc/${t}.ts`);
                const unknown = entry.optionalFields.filter((k) => !fields.has(k));
                if (unknown.length) throw new Error(`${command}: ${t} has no field(s) ${unknown.join(", ")}`);
            }
            for (const n of namesUsed(entry, row)) {
                if (generatedTypes.has(n)) imports.add(n);
                else if (!ambient.has(n)) errors.push(`${command}: type ${n} is neither generated (frontend/types/rpc/${n}.ts) nor a hand-written global`);
            }
            stubs.push(renderStub(entry, row));
        } catch (e) {
            errors.push(e.message);
        }
    }
    if (errors.length) return { errors };
    const head = [
        "// Copyright 2026, AgentMux Corp.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// @generated by scripts/gen-rpc-stubs.mjs from frontend/types/rpc/rpc-schema.json (srv's",
        "// typed commands) and generated-manifest.json. DO NOT EDIT: change the Rust types or the",
        "// manifest, then run `node scripts/gen-rpc-stubs.mjs`.",
        "",
        'import { RpcClient } from "../rpc-client";',
        ...[...imports].sort().map((n) => `import type { ${n} } from "@/types/rpc/${n}";`),
        "",
        "export const GeneratedApi = {",
    ];
    return { source: [...head, ...stubs, "};", ""].join("\n") };
}

/** Why the frontend isn't calling srv through generated stubs only: a hand-written stub
 *  (`hand`: method -> rpc-api file), an `RpcApi` other than `GeneratedApi` (`indexSource`, the
 *  text of rpc-api/index.ts), or a raw `.rpcCall("<command>"` in `sources` ([path, text]). */
export function generatedOnlyProblems({ hand, indexSource, sources }) {
    const errors = [];
    for (const [method, file] of hand) {
        errors.push(`rpc-api/${file}: ${method} is a hand-written stub; every stub is generated. Add its command to generated-manifest.json (srv must register it with register_typed) and delete the method`);
    }
    if (!/^export const RpcApi = GeneratedApi;$/m.test(indexSource)) {
        errors.push("rpc-api/index.ts: RpcApi must be exactly `export const RpcApi = GeneratedApi;`");
    }
    for (const [path, text] of sources) {
        text.split(/\r?\n/).forEach((line, i) => {
            const m = /\.rpcCall\(\s*["'`]([^"'`]+)["'`]/.exec(line) ?? (/\.rpcCall\(\s*$/.test(line) ? /^\s*["'`]([^"'`]+)["'`]/.exec(text.split(/\r?\n/)[i + 1] ?? "") : null);
            if (m) errors.push(`${path}:${i + 1}: calls "${m[1]}" with rpcCall directly; call its generated stub on RpcApi instead`);
        });
    }
    return errors;
}

/** The frontend's non-test sources, except the generated stubs and the RPC client itself. */
function frontendSources() {
    const out = [];
    const walk = (dir) => {
        for (const e of readdirSync(dir, { withFileTypes: true })) {
            const p = join(dir, e.name);
            if (e.isDirectory()) { if (e.name !== "node_modules") walk(p); }
            else if (/\.tsx?$/.test(e.name) && !/\.(test|spec)\.tsx?$/.test(e.name) && p !== OUT && !p.endsWith(join("store", "rpc-client.ts"))) {
                out.push([relative(ROOT, p).replace(/\\/g, "/"), readFileSync(p, "utf8")]);
            }
        }
    };
    walk(join(ROOT, "frontend"));
    return out;
}

async function main() {
    const check = process.argv.includes("--check");
    const only = generatedOnlyProblems({ hand: handWritten(), indexSource: readFileSync(join(API_DIR, "index.ts"), "utf8"), sources: frontendSources() });
    if (only.length) {
        console.error(`gen-rpc-stubs: ${only.length} RPC call(s) not through a generated stub:\n${only.map((e) => `  - ${e}`).join("\n")}`);
        process.exit(1);
    }
    const schema = JSON.parse(readFileSync(SCHEMA, "utf8"));
    const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
    const generatedTypes = new Set(readdirSync(RPC_TYPES).filter((f) => f.endsWith(".ts")).map((f) => f.slice(0, -3)));
    const fieldsOf = (t) => {
        const p = join(RPC_TYPES, `${t}.ts`);
        if (!existsSync(p)) return null;
        const body = readFileSync(p, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
        // A field starts a line, or follows `{` or `,` (ts-rs puts short types on one line).
        return new Set([...body.matchAll(/(?:^|[{,])\s*(\w+)\??:/gm)].map((m) => m[1]));
    };
    const result = generate({ schema, manifest, ambient: ambientNames(), generatedTypes, hand: handWritten(), fieldsOf });
    if (result.errors) {
        console.error(`gen-rpc-stubs: ${result.errors.length} problem(s), nothing written:\n${result.errors.map((e) => `  - ${e}`).join("\n")}`);
        process.exit(1);
    }
    const prettier = await import("prettier");
    const config = (await prettier.resolveConfig(OUT)) ?? {};
    const source = await prettier.format(result.source, { ...config, filepath: OUT });
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
    if (check) {
        if (current !== source) {
            console.error("gen-rpc-stubs: frontend/app/store/rpc-api/generated.ts is stale. Run: node scripts/gen-rpc-stubs.mjs");
            process.exit(1);
        }
        console.log(`gen-rpc-stubs: ok (${manifest.stubs.length} generated stub(s) current)`);
        return;
    }
    if (current === source) console.log(`gen-rpc-stubs: unchanged (${manifest.stubs.length} stub(s))`);
    else {
        writeFileSync(OUT, source);
        console.log(`gen-rpc-stubs: wrote ${manifest.stubs.length} stub(s) to frontend/app/store/rpc-api/generated.ts`);
    }
}

if (process.argv[1] && resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1])) main();
