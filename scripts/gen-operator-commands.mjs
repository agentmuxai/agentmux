// Generates the list of srv commands that wait for the window's proof before they are sent, from srv's own
// decision about who may call what:
//
//   crates/srv-core/src/backend/rpc/action_commands.rs   every command a connection can call
//   crates/srv-core/src/backend/rpc/action_access.rs     OPEN: the ones any connection may call
//   -> frontend/app/store/operator-commands.generated.ts  `OPERATOR_COMMANDS`: every command that is not OPEN
//
// srv refuses a command that is not open to a connection the host has not proven (`server::dispatch_guard`), so the
// app holds each of them until its own connection's proof lands (`operator-proof.ts`). A command added to
// srv is the window's alone until it is listed in OPEN, and arrives here by regenerating, so the list cannot fall
// behind the guard. The commands the window sends before its proof are exactly OPEN.
//
// Usage:
//   node scripts/gen-operator-commands.mjs           write operator-commands.generated.ts
//   node scripts/gen-operator-commands.mjs --check   fail if it is stale (CI)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { isMain } from "./lib/is-main.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const RPC_DIR = join(ROOT, "crates/srv-core/src/backend/rpc");
const OUT = join(ROOT, "frontend/app/store/operator-commands.generated.ts");
const DECIDED = ["ALWAYS", "UNLESS_OPERATOR", "LIVE_INPUT", "READ_ONLY"];

/** The strings of `pub const <name>: &[&str] = &[ ... ];` in a Rust source. */
export function constList(source, name) {
    const m = source.match(new RegExp(`pub const ${name}: &\\[&str\\] = &\\[([\\s\\S]*?)\\];`));
    if (!m) throw new Error(`no \`pub const ${name}: &[&str]\` found`);
    return [...m[1].replace(/\/\/.*$/gm, "").matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

/** The commands that wait for the window's proof: every decided command that is not open. */
export function operatorCommands(commandsSource, accessSource) {
    const open = new Set(constList(accessSource, "OPEN"));
    const decided = new Set(DECIDED.flatMap((n) => constList(commandsSource, n)));
    const missing = [...open].filter((c) => !decided.has(c));
    if (missing.length) throw new Error(`OPEN names commands that action_commands.rs does not list: ${missing.join(", ")}`);
    return [...decided].filter((c) => !open.has(c)).sort();
}

export function render(commands) {
    return [
        "// Copyright 2026, AgentMux Corp.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// @generated by scripts/gen-operator-commands.mjs from crates/srv-core/src/backend/rpc/action_commands.rs and",
        "// action_access.rs. DO NOT EDIT: decide a command in those files, then run `node scripts/gen-operator-commands.mjs`.",
        "",
        "/** srv commands only the AgentMux window may call (every one that is not in action_access.rs's OPEN): the app",
        " *  sends them once its own connection is proven (operator-proof.ts). */",
        "export const OPERATOR_COMMANDS: ReadonlySet<string> = new Set([",
        ...commands.map((c) => `    ${JSON.stringify(c)},`),
        "]);",
        "",
    ].join("\n");
}

function current() {
    const read = (f) => readFileSync(join(RPC_DIR, f), "utf8");
    return render(operatorCommands(read("action_commands.rs"), read("action_access.rs")));
}

if (isMain(import.meta.url)) {
    const text = current();
    if (process.argv.includes("--check")) {
        let have = "";
        try {
            have = readFileSync(OUT, "utf8");
        } catch {}
        if (have !== text) {
            console.error("frontend/app/store/operator-commands.generated.ts is stale: run `node scripts/gen-operator-commands.mjs`");
            process.exit(1);
        }
    } else {
        writeFileSync(OUT, text);
    }
}
